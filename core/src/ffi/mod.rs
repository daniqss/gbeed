/// Concrete `Controller` used by the C interface. Its trait implementations are generated by
/// `gbeed-macros`, calling the registered callbacks on top of the `fallback` controller
#[derive(Default)]
pub(crate) struct FfiController<D> {
    pub(crate) callbacks: GbeedController,
    pub(crate) fallback: D,
}

/// Opaque emulator handle
pub struct GbeedEmu {
    dmg: Dmg,
    controller: FfiController<BufferedController>,
}

#[repr(C)]
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum GbeedError {
    Ok = 0,
    NullPointer,
    InvalidStorage,
    InvalidBootRom,
    InvalidRomSize,
    InvalidRamSize,
    InvalidMbcRomRamCombination,
    UnsupportedCartridgeType,
    IncorrectHeaderChecksum,
    IncorrectGlobalChecksum,
    Instruction,
}

impl From<CartridgeError> for GbeedError {
    fn from(err: CartridgeError) -> Self {
        match err {
            CartridgeError::InvalidRomSize(..) => GbeedError::InvalidRomSize,
            CartridgeError::InvalidRamSize(..) => GbeedError::InvalidRamSize,
            CartridgeError::InvalidMBCRomRamCombination(..) => GbeedError::InvalidMbcRomRamCombination,
            CartridgeError::UnsupportedCartridgeType(..) => GbeedError::UnsupportedCartridgeType,
            CartridgeError::IncorrectHeaderChecksum(..) => GbeedError::IncorrectHeaderChecksum,
            CartridgeError::IncorrectGlobalChecksum(..) => GbeedError::IncorrectGlobalChecksum,
        }
    }
}

impl From<DmgError> for GbeedError {
    fn from(err: DmgError) -> Self {
        match err {
            DmgError::Instruction(_) => GbeedError::Instruction,
        }
    }
}

impl<T, E: Into<GbeedError>> From<Result<T, E>> for GbeedError {
    fn from(result: Result<T, E>) -> Self { result.map_or_else(Into::into, |_| GbeedError::Ok) }
}

#[repr(C)]
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum GbeedButton {
    Right = 0,
    Left,
    Up,
    Down,
    A,
    B,
    Select,
    Start,
}

impl From<GbeedButton> for JoypadButton {
    fn from(button: GbeedButton) -> Self {
        match button {
            GbeedButton::Right => JoypadButton::Right,
            GbeedButton::Left => JoypadButton::Left,
            GbeedButton::Up => JoypadButton::Up,
            GbeedButton::Down => JoypadButton::Down,
            GbeedButton::A => JoypadButton::A,
            GbeedButton::B => JoypadButton::B,
            GbeedButton::Select => JoypadButton::Select,
            GbeedButton::Start => JoypadButton::Start,
        }
    }
}

/// Builds a slice from a C buffer, NULL meaning no buffer
unsafe fn optional_slice<'a, T>(data: *const T, len: usize) -> Option<&'a [T]> {
    // SAFETY: the caller guarantees `data` is NULL or valid for `len` elements
    (!data.is_null()).then(|| unsafe { slice::from_raw_parts(data, len) })
}

unsafe fn write_out<T>(out: *mut T, value: T) {
    if let Some(out) = unsafe { out.as_mut() } {
        *out = value;
    }
}

/// Bytes of memory needed to hold an emulator
#[unsafe(no_mangle)]
pub extern "C" fn gbeed_emu_size() -> usize { mem::size_of::<GbeedEmu>() }

/// Alignment required for the memory holding an emulator
#[unsafe(no_mangle)]
pub extern "C" fn gbeed_emu_align() -> usize { mem::align_of::<GbeedEmu>() }

/// Builds an emulator inside `storage`, which must be aligned to `gbeed_emu_align()` and have
/// at least `gbeed_emu_size()` bytes. `rom`, `boot_rom` and `save` are copied, so they can be freed afterwards.
///
/// `boot_rom` (256 bytes) and `save` are optional (NULL). Without a boot ROM the emulator starts
/// in the post boot state.
/// Returns `storage` as the emulator handle, or NULL on failure, writing the reason to `error` if it is not NULL.
/// The emulator must be released with `gbeed_deinit` before freeing `storage`.
///
/// # Safety
/// `storage` must be valid for `storage_len` bytes and not hold a live emulator, every other non NULL pointer
/// must be valid for its length, and `error` must be NULL or writable.
#[unsafe(no_mangle)]
#[allow(clippy::too_many_arguments)]
pub unsafe extern "C" fn gbeed_init(
    storage: *mut c_void,
    storage_len: usize,
    rom: *const u8,
    rom_len: usize,
    boot_rom: *const u8,
    boot_rom_len: usize,
    save: *const u8,
    save_len: usize,
    error: *mut GbeedError,
) -> *mut GbeedEmu {
    let emu = storage.cast::<GbeedEmu>();

    let result = (|| {
        if emu.is_null() {
            return Err(GbeedError::NullPointer);
        }
        if storage_len < mem::size_of::<GbeedEmu>() || !emu.is_aligned() {
            return Err(GbeedError::InvalidStorage);
        }

        let rom = unsafe { optional_slice(rom, rom_len) }.ok_or(GbeedError::NullPointer)?;
        let boot_rom = unsafe { optional_slice(boot_rom, boot_rom_len) };
        let save = unsafe { optional_slice(save, save_len) };

        if boot_rom.is_some_and(|boot| boot.len() != BOOT_ROM_SIZE as usize) {
            return Err(GbeedError::InvalidBootRom);
        }

        let cartridge = Cartridge::new(rom, save)?;

        // SAFETY: checked above that `storage` is big enough and aligned
        unsafe {
            emu.write(GbeedEmu {
                dmg: Dmg::new(cartridge, boot_rom),
                controller: FfiController::default(),
            })
        };

        Ok(emu)
    })();

    let (emu, err) = match result {
        Ok(emu) => (emu, GbeedError::Ok),
        Err(err) => (ptr::null_mut(), err),
    };

    unsafe { write_out(error, err) };
    emu
}

/// Releases the resources of an emulator built with `gbeed_init`, its storage can be freed afterwards.
/// NULL is ignored.
///
/// # Safety
/// `emu` must be NULL or a handle returned by `gbeed_init` not released yet.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn gbeed_deinit(emu: *mut GbeedEmu) {
    if !emu.is_null() {
        unsafe { ptr::drop_in_place(emu) };
    }
}

/// Registers the callbacks used by the emulator, the struct is copied.
/// NULL unregisters every callback.
///
/// # Safety
/// `emu` must be NULL or a valid handle, `controller` NULL or a valid `GbeedController`,
/// and its callbacks must stay valid for as long as they are registered.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn gbeed_set_controller(emu: *mut GbeedEmu, controller: *const GbeedController) {
    if let Some(emu) = unsafe { emu.as_mut() } {
        emu.controller.callbacks = unsafe { controller.as_ref() }.copied().unwrap_or_default();
    }
}

/// Runs the emulator for a whole frame (70224 T-cycles)
///
/// # Safety
/// `emu` must be NULL or a valid handle.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn gbeed_run_frame(emu: *mut GbeedEmu) -> GbeedError {
    let Some(emu) = (unsafe { emu.as_mut() }) else {
        return GbeedError::NullPointer;
    };

    emu.dmg.run(&mut emu.controller).into()
}

/// Executes a single CPU instruction
///
/// # Safety
/// `emu` must be NULL or a valid handle.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn gbeed_step(emu: *mut GbeedEmu) -> GbeedError {
    let Some(emu) = (unsafe { emu.as_mut() }) else {
        return GbeedError::NullPointer;
    };

    emu.dmg.step(&mut emu.controller).into()
}

/// # Safety
/// `emu` must be NULL or a valid handle.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn gbeed_reset(emu: *mut GbeedEmu) {
    if let Some(emu) = unsafe { emu.as_mut() } {
        emu.dmg.reset();
    }
}

/// # Safety
/// `emu` must be NULL or a valid handle, and `button` a valid `GbeedButton` value.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn gbeed_set_button(emu: *mut GbeedEmu, button: GbeedButton, pressed: bool) {
    if let Some(emu) = unsafe { emu.as_mut() } {
        emu.dmg.joypad.button_down(button.into(), pressed);
    }
}

/// Last complete frame, `GB_SCREEN_WIDTH * GB_SCREEN_HEIGHT` bytes in row major order,
/// one shade (0..=3) per pixel. The pointer stays valid until the emulator is released.
///
/// # Safety
/// `emu` must be NULL or a valid handle.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn gbeed_framebuffer(emu: *const GbeedEmu) -> *const u8 {
    unsafe { emu.as_ref() }.map_or(ptr::null(), |emu| emu.controller.fallback.framebuffer().as_ptr())
}

/// Drains the audio buffer, returning the interleaved stereo samples (L, R, L, R...) generated
/// since the last call, and writing their count to `len`. Holds up to `GB_STEREO_AUDIO_BUFFER_SIZE`
/// samples, newer ones are dropped when full.
/// The samples stay valid until the next `gbeed_run_frame` or `gbeed_step`.
///
/// # Safety
/// `emu` must be NULL or a valid handle, and `len` NULL or writable.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn gbeed_audio_samples(emu: *mut GbeedEmu, len: *mut usize) -> *const i16 {
    let samples = unsafe { emu.as_mut() }.map_or(&[][..], |emu| emu.controller.fallback.drain_audio());

    unsafe { write_out(len, samples.len()) };
    samples.as_ptr()
}

/// Cartridge RAM to persist as a save file, writing its size to `len`.
/// Returns NULL when the cartridge does not support saves.
/// The data stays valid until the next `gbeed_run_frame` or `gbeed_step`.
///
/// # Safety
/// `emu` must be NULL or a valid handle, and `len` NULL or writable.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn gbeed_save_data(emu: *const GbeedEmu, len: *mut usize) -> *const u8 {
    let save = unsafe { emu.as_ref() }.and_then(|emu| emu.dmg.cartridge.save_game());

    unsafe { write_out(len, save.map_or(0, <[u8]>::len)) };
    save.map_or(ptr::null(), <[u8]>::as_ptr)
}

/// Static, NUL terminated description of an error
#[unsafe(no_mangle)]
pub extern "C" fn gbeed_error_message(error: GbeedError) -> *const c_char {
    let message = match error {
        GbeedError::Ok => c"no error",
        GbeedError::NullPointer => c"unexpected NULL pointer",
        GbeedError::InvalidStorage => c"emulator storage too small or misaligned",
        GbeedError::InvalidBootRom => c"boot ROM must be 256 bytes long",
        GbeedError::InvalidRomSize => c"invalid ROM size",
        GbeedError::InvalidRamSize => c"invalid RAM size",
        GbeedError::InvalidMbcRomRamCombination => c"invalid MBC, ROM and RAM combination",
        GbeedError::UnsupportedCartridgeType => c"unsupported cartridge type",
        GbeedError::IncorrectHeaderChecksum => c"incorrect header checksum",
        GbeedError::IncorrectGlobalChecksum => c"incorrect global checksum",
        GbeedError::Instruction => c"the CPU executed an invalid instruction",
    };

    message.as_ptr()
}
