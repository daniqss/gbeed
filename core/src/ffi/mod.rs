//! C interface of gbeed, enabled with the `ffi` feature. Usable without `std` nor `alloc`.
//!
//! The emulator is exposed as the opaque `GbeedEmu`, built inside memory provided by the host,
//! so it can live in a static buffer on embedded targets.
//! The `Controller` trait becomes `GbeedController`, generated from the platform traits by the
//! `gbeed-macros` crate: a struct of optional callbacks grouped by trait, plus a `user_data`
//! pointer given back to every callback.
//! The frame and the audio are always kept in internal buffers, read with `gbeed_framebuffer` and
//! `gbeed_audio_samples` once `gbeed_run_frame` returns, so callbacks are only needed for
//! notifications or per pixel/sample processing.
//!
//! Callbacks run while the emulator is borrowed, so they must not call any `gbeed_*` function
//! on the same handle.

